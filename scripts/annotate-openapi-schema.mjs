/**
 * Adds a stable provenance header to the openapi-typescript output.
 *
 * The generated definitions below the header are never hand-written or edited;
 * this script only prepends fixed comments so the committed schema and CI
 * regeneration are byte-for-byte identical and traceable to a backend commit.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const schemaPath = resolve(root, 'src/api/generated/schema.d.ts');
const generated = await readFile(schemaPath, 'utf8');

const header = `/**
 * Generated from the pinned backend OpenAPI snapshot. DO NOT EDIT BY HAND.
 *
 * Source: openapi-spec/openapi-620f7a795cc67a16e905115131f561bbd986af85.json
 * Backend commit: 620f7a795cc67a16e905115131f561bbd986af85
 * Backend Actions run: 44395699755 (artifact openapi-620f7a795cc67a16e905115131f561bbd986af85)
 * SHA-256: 9533c5a5a9ce3044b2543cabaa7db09952b26c9e8581e08baf9889c33df2843d
 * Generator: openapi-typescript 7.13.0; regenerate with \`npm run types:generate\`.
 * See docs/PHASE1_STEP1_CONTRACT_NOTES.md §14 for the snapshot update procedure.
 */

`;

const marker = 'This file was auto-generated by openapi-typescript.';
if (!generated.includes(marker)) {
  console.error('Generated schema does not look like openapi-typescript output; refusing to annotate.');
  process.exit(1);
}
const body = generated.startsWith('/**') ? generated.slice(generated.indexOf('*/') + 2).trimStart() : generated;
await writeFile(schemaPath, header + body, 'utf8');
console.log(`Annotated provenance header: ${schemaPath}`);
